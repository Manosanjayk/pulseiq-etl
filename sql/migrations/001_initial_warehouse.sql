CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS dim_department (
    department_id text PRIMARY KEY,
    department_name text NOT NULL,
    cost_center text NOT NULL,
    description text NOT NULL,
    is_leadership boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS dim_location (
    work_location text PRIMARY KEY,
    state text NOT NULL,
    city_tier text NOT NULL,
    tier_number smallint NOT NULL CHECK (tier_number >= 0)
);

CREATE TABLE IF NOT EXISTS dim_leave_type (
    leave_type_code text PRIMARY KEY,
    leave_type_name text NOT NULL,
    pay_type text NOT NULL CHECK (pay_type IN ('Paid', 'Unpaid')),
    annual_quota_days numeric(8, 2) NOT NULL CHECK (annual_quota_days >= 0),
    prorated_for_joiners boolean NOT NULL,
    carry_forward_allowed boolean NOT NULL,
    max_carry_forward_days numeric(8, 2) NOT NULL CHECK (max_carry_forward_days >= 0),
    policy_note text NOT NULL
);

CREATE TABLE IF NOT EXISTS dim_date (
    date_key integer PRIMARY KEY,
    date_value date NOT NULL UNIQUE,
    calendar_year smallint NOT NULL,
    quarter smallint NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    month_number smallint NOT NULL CHECK (month_number BETWEEN 1 AND 12),
    month_name text NOT NULL,
    year_month text NOT NULL,
    week_of_year smallint NOT NULL CHECK (week_of_year BETWEEN 1 AND 53),
    day_of_week text NOT NULL,
    is_weekend boolean NOT NULL,
    is_holiday boolean NOT NULL,
    is_working_day boolean NOT NULL,
    financial_year text NOT NULL,
    fiscal_quarter text NOT NULL,
    fiscal_month_number smallint NOT NULL CHECK (fiscal_month_number BETWEEN 1 AND 12),
    is_month_end boolean NOT NULL,
    month_start_date date NOT NULL,
    month_end_date date NOT NULL,
    CHECK (month_start_date <= date_value AND date_value <= month_end_date)
);

CREATE TABLE IF NOT EXISTS dim_role (
    role_id text PRIMARY KEY,
    department_id text NOT NULL REFERENCES dim_department(department_id),
    role_title text NOT NULL,
    level smallint NOT NULL CHECK (level >= 0),
    grade text NOT NULL,
    band_min_annual numeric(18, 2) NOT NULL CHECK (band_min_annual >= 0),
    band_mid_annual numeric(18, 2) NOT NULL CHECK (band_mid_annual >= 0),
    band_max_annual numeric(18, 2) NOT NULL CHECK (band_max_annual >= 0),
    overtime_eligible boolean NOT NULL,
    band_reference_year smallint NOT NULL,
    CHECK (band_min_annual <= band_mid_annual AND band_mid_annual <= band_max_annual)
);

CREATE TABLE IF NOT EXISTS dim_employee (
    employee_sk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_employee_key bigint NOT NULL UNIQUE,
    employee_id text NOT NULL,
    full_name text NOT NULL,
    gender text NOT NULL,
    date_of_birth date NOT NULL,
    hire_date date NOT NULL,
    exit_date date,
    employment_status text NOT NULL,
    employment_type text NOT NULL,
    department_id text NOT NULL REFERENCES dim_department(department_id),
    role_id text NOT NULL REFERENCES dim_role(role_id),
    role_title text NOT NULL,
    job_level smallint NOT NULL CHECK (job_level >= 0),
    manager_employee_id text,
    manager_sk bigint REFERENCES dim_employee(employee_sk) DEFERRABLE INITIALLY DEFERRED,
    work_location text NOT NULL REFERENCES dim_location(work_location),
    work_mode text NOT NULL,
    highest_education text NOT NULL,
    valid_from date NOT NULL,
    valid_to date NOT NULL,
    source_valid_to date NOT NULL,
    is_current boolean NOT NULL,
    change_reason text NOT NULL,
    tenure_years numeric(8, 2) CHECK (tenure_years >= 0),
    CHECK (valid_from <= valid_to),
    CHECK (hire_date <= COALESCE(exit_date, DATE '9999-12-31')),
    EXCLUDE USING gist (
        employee_id WITH =,
        daterange(valid_from, valid_to, '[]') WITH &&
    ) DEFERRABLE INITIALLY DEFERRED
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_dim_employee_one_current
    ON dim_employee(employee_id) WHERE is_current;
CREATE INDEX IF NOT EXISTS ix_dim_employee_department_dates
    ON dim_employee(department_id, valid_from, valid_to);
CREATE INDEX IF NOT EXISTS ix_dim_employee_role
    ON dim_employee(role_id);

CREATE TABLE IF NOT EXISTS warehouse_batch (
    batch_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    status text NOT NULL CHECK (status IN ('running', 'success', 'failed')),
    source_directory text NOT NULL,
    source_counts jsonb NOT NULL DEFAULT '{}'::jsonb,
    accepted_counts jsonb NOT NULL DEFAULT '{}'::jsonb,
    rejected_counts jsonb NOT NULL DEFAULT '{}'::jsonb,
    reconciliation jsonb NOT NULL DEFAULT '{}'::jsonb,
    error_message text
);

CREATE TABLE IF NOT EXISTS warehouse_rejection (
    rejection_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id bigint NOT NULL REFERENCES warehouse_batch(batch_id) ON DELETE CASCADE,
    source_table text NOT NULL,
    source_key text,
    rejection_reason text NOT NULL,
    source_record jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_warehouse_rejection_batch
    ON warehouse_rejection(batch_id, source_table);

CREATE TABLE IF NOT EXISTS fact_attendance_monthly (
    attendance_fact_id text PRIMARY KEY,
    employee_id text NOT NULL,
    employee_sk bigint NOT NULL REFERENCES dim_employee(employee_sk),
    date_key integer NOT NULL REFERENCES dim_date(date_key),
    department_id text NOT NULL REFERENCES dim_department(department_id),
    scheduled_days smallint NOT NULL CHECK (scheduled_days >= 0),
    present_days smallint NOT NULL CHECK (present_days >= 0),
    wfh_days numeric(8, 2) NOT NULL CHECK (wfh_days >= 0),
    half_days_unpaid numeric(8, 2) NOT NULL CHECK (half_days_unpaid >= 0),
    paid_leave_days numeric(8, 2) NOT NULL CHECK (paid_leave_days >= 0),
    unpaid_absence_days numeric(8, 2) NOT NULL CHECK (unpaid_absence_days >= 0),
    late_arrivals smallint NOT NULL CHECK (late_arrivals >= 0),
    avg_hours_worked numeric(8, 2) NOT NULL CHECK (avg_hours_worked >= 0),
    overtime_hours numeric(10, 2) NOT NULL CHECK (overtime_hours >= 0),
    attendance_rate numeric(8, 5) NOT NULL CHECK (attendance_rate BETWEEN 0 AND 1),
    period_end_date date NOT NULL REFERENCES dim_date(date_value),
    batch_id bigint NOT NULL REFERENCES warehouse_batch(batch_id)
);
CREATE INDEX IF NOT EXISTS ix_attendance_month_department
    ON fact_attendance_monthly(period_end_date, department_id);
CREATE INDEX IF NOT EXISTS ix_attendance_employee_period
    ON fact_attendance_monthly(employee_sk, period_end_date);

CREATE TABLE IF NOT EXISTS fact_payroll (
    payroll_item_id text PRIMARY KEY,
    run_id text NOT NULL,
    employee_id text NOT NULL,
    employee_sk bigint NOT NULL REFERENCES dim_employee(employee_sk),
    date_key integer NOT NULL REFERENCES dim_date(date_key),
    period_end_date date NOT NULL REFERENCES dim_date(date_value),
    department_id text NOT NULL REFERENCES dim_department(department_id),
    role_id text NOT NULL REFERENCES dim_role(role_id),
    payable_days numeric(8, 2) NOT NULL CHECK (payable_days >= 0),
    lop_days numeric(8, 2) NOT NULL CHECK (lop_days >= 0),
    overtime_hours_paid numeric(10, 2) NOT NULL CHECK (overtime_hours_paid >= 0),
    variable_pay_type text,
    monthly_fixed_gross numeric(18, 2) NOT NULL CHECK (monthly_fixed_gross >= 0),
    basic numeric(18, 2) NOT NULL CHECK (basic >= 0),
    hra numeric(18, 2) NOT NULL CHECK (hra >= 0),
    conveyance numeric(18, 2) NOT NULL CHECK (conveyance >= 0),
    medical numeric(18, 2) NOT NULL CHECK (medical >= 0),
    special_allowance numeric(18, 2) NOT NULL CHECK (special_allowance >= 0),
    earned_fixed_pay numeric(18, 2) NOT NULL CHECK (earned_fixed_pay >= 0),
    overtime_pay numeric(18, 2) NOT NULL CHECK (overtime_pay >= 0),
    variable_pay numeric(18, 2) NOT NULL CHECK (variable_pay >= 0),
    gross_pay numeric(18, 2) NOT NULL CHECK (gross_pay >= 0),
    pf_employee numeric(18, 2) NOT NULL CHECK (pf_employee >= 0),
    esi_employee numeric(18, 2) NOT NULL CHECK (esi_employee >= 0),
    professional_tax numeric(18, 2) NOT NULL CHECK (professional_tax >= 0),
    tds numeric(18, 2) NOT NULL CHECK (tds >= 0),
    other_deductions numeric(18, 2) NOT NULL CHECK (other_deductions >= 0),
    total_deductions numeric(18, 2) NOT NULL CHECK (total_deductions >= 0),
    net_pay numeric(18, 2) NOT NULL CHECK (net_pay >= 0),
    pf_employer numeric(18, 2) NOT NULL CHECK (pf_employer >= 0),
    esi_employer numeric(18, 2) NOT NULL CHECK (esi_employer >= 0),
    employer_cost numeric(18, 2) NOT NULL CHECK (employer_cost >= 0),
    headcount_flag smallint NOT NULL CHECK (headcount_flag IN (0, 1)),
    batch_id bigint NOT NULL REFERENCES warehouse_batch(batch_id)
);
CREATE INDEX IF NOT EXISTS ix_payroll_period_department
    ON fact_payroll(period_end_date, department_id);
CREATE INDEX IF NOT EXISTS ix_payroll_run_period
    ON fact_payroll(run_id, period_end_date);
CREATE INDEX IF NOT EXISTS ix_payroll_employee_period
    ON fact_payroll(employee_sk, period_end_date);

CREATE TABLE IF NOT EXISTS fact_leave (
    leave_request_id text PRIMARY KEY,
    employee_id text NOT NULL,
    employee_sk bigint NOT NULL REFERENCES dim_employee(employee_sk),
    leave_type_code text NOT NULL REFERENCES dim_leave_type(leave_type_code),
    start_date_key integer NOT NULL REFERENCES dim_date(date_key),
    end_date_key integer NOT NULL REFERENCES dim_date(date_key),
    start_date date NOT NULL REFERENCES dim_date(date_value),
    end_date date NOT NULL REFERENCES dim_date(date_value),
    days numeric(8, 2) NOT NULL CHECK (days >= 0),
    status text NOT NULL,
    applied_on date NOT NULL,
    decided_on date,
    approver_id text,
    reason text NOT NULL,
    batch_id bigint NOT NULL REFERENCES warehouse_batch(batch_id),
    CHECK (start_date <= end_date)
);
CREATE INDEX IF NOT EXISTS ix_leave_start_status_type
    ON fact_leave(start_date, status, leave_type_code);
CREATE INDEX IF NOT EXISTS ix_leave_employee_start
    ON fact_leave(employee_sk, start_date);

CREATE TABLE IF NOT EXISTS fact_headcount_monthly (
    month_end_date date NOT NULL REFERENCES dim_date(date_value),
    department_id text NOT NULL REFERENCES dim_department(department_id),
    employee_count integer NOT NULL CHECK (employee_count >= 0),
    new_hires integer NOT NULL CHECK (new_hires >= 0),
    attrition_count integer NOT NULL CHECK (attrition_count >= 0),
    batch_id bigint NOT NULL REFERENCES warehouse_batch(batch_id),
    PRIMARY KEY (month_end_date, department_id)
);
CREATE INDEX IF NOT EXISTS ix_headcount_department_month
    ON fact_headcount_monthly(department_id, month_end_date);